// Package gen generates Protobuf marshalers and unmarshalers for the Go
// structs protoc-gen-go produces, built on top of the cfprotobuf runtime
// package.
package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// DefaultRuntime is the import path of the runtime package generated code
// uses, unless Config.Runtime says otherwise.
const DefaultRuntime = "github.com/centrifugal/protocol/cfprotobuf"

// Config describes what to generate.
type Config struct {
	// Files are the Go source files with the structs, all of one package.
	Files []string
	// Types limits generation to the listed structs. All structs of Files
	// which have fields with a protobuf tag are used if it is empty.
	Types []string
	// Suffix is what the names of generated methods end with: MarshalVT,
	// UnmarshalVT and so on by default, the names vtprotobuf uses.
	Suffix string
	// Runtime is the import path of the cfprotobuf runtime package.
	Runtime string
	// DropUnknown makes generated unmarshalers skip the fields a message does
	// not have instead of keeping them with the message. It is for code which
	// decodes input it has no reason to pass on, such as a server decoding
	// what clients send: there is then nothing to keep, to account for, or to
	// leak into a message marshaled later.
	DropUnknown bool
}

type kind int

const (
	kString kind = iota
	kBytes
	kBool
	kVarint
	kZigzag
	kFixed
	kMessage
)

// value is the type of a field, of an element of a repeated field, or of a
// map value.
type value struct {
	kind kind
	// src is the Go type as written in the source. For kMessage it is the
	// struct the pointer points to.
	src string
	// size is the number of bytes of a kFixed value: 4 for a float32, 8 for a
	// float64.
	size int
}

type field struct {
	goName   string
	number   int
	repeated bool
	// isMap is set for map fields, val is then the type of map values and
	// keySrc the Go type of the keys, which are strings.
	isMap  bool
	keySrc string
	val    value
}

type structInfo struct {
	name   string
	fields []field
	// unknown is set if the struct has the unknownFields field protoc-gen-go
	// adds, which is where fields the type does not know are kept.
	unknown bool
	// recursive is set if a message of the type may have a message of the
	// same type inside.
	recursive bool
}

type generator struct {
	cfg   Config
	decls map[string]ast.Expr
	buf   bytes.Buffer
}

var scalarKinds = map[string]bool{
	"bool": true, "int32": true, "int64": true, "uint32": true, "uint64": true, "float32": true, "float64": true,
}

// Generate returns the source of a Go file with methods for the structs cfg
// selects.
func Generate(cfg Config) ([]byte, error) {
	if cfg.Suffix == "" {
		cfg.Suffix = "VT"
	}
	if cfg.Runtime == "" {
		cfg.Runtime = DefaultRuntime
	}
	g := &generator{cfg: cfg, decls: map[string]ast.Expr{}}

	var pkg string
	var order []string
	fset := token.NewFileSet()
	for _, name := range cfg.Files {
		f, err := parser.ParseFile(fset, name, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		if pkg != "" && pkg != f.Name.Name {
			return nil, fmt.Errorf("files belong to different packages: %s and %s", pkg, f.Name.Name)
		}
		pkg = f.Name.Name
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || ts.TypeParams != nil {
					continue
				}
				g.decls[ts.Name.Name] = ts.Type
				if st, ok := ts.Type.(*ast.StructType); ok && isMessage(st) {
					order = append(order, ts.Name.Name)
				}
			}
		}
	}
	if pkg == "" {
		return nil, fmt.Errorf("no input files")
	}
	if len(cfg.Types) > 0 {
		for _, name := range cfg.Types {
			if _, ok := g.decls[name].(*ast.StructType); !ok {
				return nil, fmt.Errorf("type %s is not a struct declared in the input files", name)
			}
		}
		order = cfg.Types
	}

	structs := make([]structInfo, 0, len(order))
	for _, name := range order {
		st, _ := g.decls[name].(*ast.StructType)
		si, err := g.structInfo(name, st)
		if err != nil {
			return nil, err
		}
		structs = append(structs, si)
	}
	markRecursive(structs)

	for n := range structs {
		g.size(&structs[n])
		g.marshal(&structs[n])
		g.unmarshal(&structs[n])
	}
	body := g.buf.String()

	var out bytes.Buffer
	out.WriteString("// Code generated by cfprotobuf. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\nimport (\n", pkg)
	if strings.Contains(body, "binary.") {
		out.WriteString("\t\"encoding/binary\"\n")
	}
	if strings.Contains(body, "math.") {
		out.WriteString("\t\"math\"\n")
	}
	fmt.Fprintf(&out, "\n\tcfprotobuf %q\n)\n", cfg.Runtime)
	out.WriteString(body)
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("generated code does not compile, this is a bug in cfprotobuf: %w", err)
	}
	return src, nil
}

// isMessage reports whether a struct has a field with a protobuf tag, or is
// an empty message as protoc-gen-go writes it.
func isMessage(st *ast.StructType) bool {
	for _, f := range st.Fields.List {
		if f.Tag != nil && strings.Contains(f.Tag.Value, "protobuf:") {
			return true
		}
		for _, name := range f.Names {
			if name.Name == "unknownFields" || name.Name == "sizeCache" {
				return true
			}
		}
	}
	return false
}

func (g *generator) p(line string, args ...any) {
	if len(args) == 0 {
		g.buf.WriteString(line)
	} else {
		fmt.Fprintf(&g.buf, line, args...)
	}
	g.buf.WriteByte('\n')
}

func (g *generator) structInfo(name string, st *ast.StructType) (structInfo, error) {
	si := structInfo{name: name}
	seen := map[int]string{}
	for _, f := range st.Fields.List {
		for _, ident := range f.Names {
			if ident.Name == "unknownFields" {
				si.unknown = true
			}
		}
		if f.Tag == nil {
			continue
		}
		unquoted, err := strconv.Unquote(f.Tag.Value)
		if err != nil {
			return si, fmt.Errorf("%s: bad struct tag %s", name, f.Tag.Value)
		}
		tag := reflect.StructTag(unquoted)
		desc, ok := tag.Lookup("protobuf")
		if !ok {
			continue
		}
		if len(f.Names) != 1 {
			return si, fmt.Errorf("%s: a protobuf tag on a field without a single name", name)
		}
		fd := field{goName: f.Names[0].Name}
		where := name + "." + fd.goName

		// The tag is "wire,number,label,name=...,proto3" and so on.
		parts := strings.Split(desc, ",")
		if len(parts) < 3 {
			return si, fmt.Errorf("%s: bad protobuf tag %q", where, desc)
		}
		if fd.number, err = strconv.Atoi(parts[1]); err != nil || fd.number < 1 || fd.number > 1<<29-1 {
			return si, fmt.Errorf("%s: bad field number in protobuf tag %q", where, desc)
		}
		if other, dup := seen[fd.number]; dup {
			return si, fmt.Errorf("%s: field number %d is also used by %s", where, fd.number, other)
		}
		seen[fd.number] = fd.goName
		for _, opt := range parts[3:] {
			if opt == "oneof" || opt == "packed" || strings.HasPrefix(opt, "enum=") || strings.HasPrefix(opt, "def=") {
				return si, fmt.Errorf("%s: protobuf tag option %q is not supported", where, opt)
			}
		}
		// Zero values left out and strings checked to be UTF-8 are the rules
		// of proto3, a proto2 field has other ones.
		if !slices.Contains(parts[3:], "proto3") {
			return si, fmt.Errorf("%s: only proto3 fields are supported", where)
		}
		if parts[2] != "opt" && parts[2] != "rep" {
			return si, fmt.Errorf("%s: protobuf label %q is not supported", where, parts[2])
		}
		fd.repeated = parts[2] == "rep"

		expr := f.Type
		if m, isMap := expr.(*ast.MapType); isMap {
			keyDesc, valDesc := tag.Get("protobuf_key"), tag.Get("protobuf_val")
			if !fd.repeated || !strings.HasPrefix(keyDesc, "bytes,1,") || !strings.Contains(valDesc+",", ",2,") {
				return si, fmt.Errorf("%s: unsupported map tags", where)
			}
			if key, kerr := g.value(m.Key, "bytes"); kerr != nil || key.kind != kString {
				return si, fmt.Errorf("%s: only maps with string keys are supported", where)
			}
			fd.isMap = true
			fd.keySrc = types.ExprString(m.Key)
			if strings.Contains(valDesc, ",enum=") {
				return si, fmt.Errorf("%s: enum map values are not supported", where)
			}
			if fd.val, err = g.value(m.Value, strings.SplitN(valDesc, ",", 2)[0]); err != nil {
				return si, fmt.Errorf("%s: %w", where, err)
			}
			si.fields = append(si.fields, fd)
			continue
		}
		if fd.repeated {
			arr, isSlice := expr.(*ast.ArrayType)
			if !isSlice || arr.Len != nil {
				return si, fmt.Errorf("%s: a repeated field must be a slice", where)
			}
			expr = arr.Elt
		}
		if fd.val, err = g.value(expr, parts[0]); err != nil {
			return si, fmt.Errorf("%s: %w", where, err)
		}
		if fd.repeated && fd.val.kind != kMessage && fd.val.kind != kString {
			return si, fmt.Errorf("%s: repeated fields of type %s are not supported", where, fd.val.src)
		}
		si.fields = append(si.fields, fd)
	}
	sort.Slice(si.fields, func(i, j int) bool { return si.fields[i].number < si.fields[j].number })
	return si, nil
}

// underlying returns the name of the predeclared type a type is based on, or
// "[]byte", or "" if it is something else.
func (g *generator) underlying(expr ast.Expr) string {
	for depth := 0; depth < 10; depth++ {
		switch e := expr.(type) {
		case *ast.Ident:
			if decl, ok := g.decls[e.Name]; ok {
				expr = decl
				continue
			}
			return e.Name
		case *ast.ArrayType:
			if id, ok := e.Elt.(*ast.Ident); ok && e.Len == nil && (id.Name == "byte" || id.Name == "uint8") {
				return "[]byte"
			}
		}
		return ""
	}
	return ""
}

// value works out how a Go type is encoded given the wire encoding its tag
// names.
func (g *generator) value(expr ast.Expr, wire string) (value, error) {
	src := types.ExprString(expr)
	v := value{src: src}
	if star, ok := expr.(*ast.StarExpr); ok {
		id, isIdent := star.X.(*ast.Ident)
		if !isIdent {
			return v, fmt.Errorf("unsupported type %s", src)
		}
		if _, isStruct := g.decls[id.Name].(*ast.StructType); !isStruct || wire != "bytes" {
			return v, fmt.Errorf("unsupported type %s", src)
		}
		v.kind, v.src = kMessage, id.Name
		return v, nil
	}
	under := g.underlying(expr)
	switch {
	case under == "string" && wire == "bytes":
		v.kind = kString
	case under == "[]byte" && wire == "bytes":
		v.kind = kBytes
	case under == "bool" && wire == "varint":
		v.kind = kBool
	case wire == "varint" && scalarKinds[under] && !strings.HasPrefix(under, "float"):
		v.kind = kVarint
	case wire == "zigzag64" && under == "int64":
		v.kind = kZigzag
	case wire == "fixed32" && under == "float32":
		v.kind, v.size = kFixed, 4
	case wire == "fixed64" && under == "float64":
		v.kind, v.size = kFixed, 8
	default:
		return v, fmt.Errorf("unsupported type %s with encoding %q", src, wire)
	}
	return v, nil
}

// markRecursive finds the structs which can be reached from themselves.
func markRecursive(structs []structInfo) {
	edges := map[string][]string{}
	for _, si := range structs {
		for _, f := range si.fields {
			if f.val.kind == kMessage {
				edges[si.name] = append(edges[si.name], f.val.src)
			}
		}
	}
	for n := range structs {
		seen := map[string]bool{}
		var visit func(name string) bool
		visit = func(name string) bool {
			for _, next := range edges[name] {
				if next == structs[n].name {
					return true
				}
				if !seen[next] {
					seen[next] = true
					if visit(next) {
						return true
					}
				}
			}
			return false
		}
		structs[n].recursive = visit(structs[n].name)
	}
}

// conv returns x converted to the type to, or x itself if it has that type
// already.
func conv(to, from, x string) string {
	if to == from {
		return x
	}
	return to + "(" + x + ")"
}

// wireType returns the wire type values of a kind are encoded with.
func wireType(v value) int {
	switch v.kind {
	case kBool, kVarint, kZigzag:
		return 0
	case kFixed:
		if v.size == 8 {
			return 1
		}
		return 5
	}
	return 2
}

// tagOf returns the tag of a field: its number and wire type.
func tagOf(number, wire int) uint64 {
	return uint64(number)<<3 | uint64(wire) //nolint:gosec // G115: number is 1..2^29-1, wire is 0..5.
}

// tagBytes returns the varint encoding of a tag.
func tagBytes(tag uint64) []byte {
	var out []byte
	for tag >= 0x80 {
		out = append(out, byte(tag)|0x80)
		tag >>= 7
	}
	return append(out, byte(tag))
}

// putTag emits code writing a tag in front of what has been written so far.
func (g *generator) putTag(tag uint64) {
	tb := tagBytes(tag)
	for n := len(tb) - 1; n >= 0; n-- {
		g.p("i--")
		g.p("b[i] = %#x", tb[n])
	}
}

func (g *generator) method(name string) string {
	return name + g.cfg.Suffix
}

// notZero returns the condition under which a singular field is written:
// proto3 leaves out fields which hold the zero value.
func notZero(v value, x string) string {
	switch v.kind {
	case kString:
		return x + ` != ""`
	case kBytes:
		return "len(" + x + ") > 0"
	case kBool:
		return x
	case kMessage:
		return x + " != nil"
	}
	return x + " != 0"
}

func (g *generator) size(si *structInfo) {
	g.p("")
	g.p("// %s returns the size of the Protobuf encoding of m.", g.method("Size"))
	g.p("func (m *%s) %s() (n int) {", si.name, g.method("Size"))
	g.p("if m == nil {")
	g.p("return 0")
	g.p("}")
	for _, f := range si.fields {
		tagSize := len(tagBytes(tagOf(f.number, 2)))
		x := "m." + f.goName
		switch {
		case f.isMap:
			// A map is a repeated message with the key in field 1 and the
			// value in field 2, both always written.
			// Starting to iterate over a map is not free even when the map
			// is empty, and most maps of most messages are.
			g.p("if len(%s) > 0 {", x)
			if f.val.kind == kBool || f.val.kind == kFixed {
				g.p("for k := range %s {", x)
			} else {
				g.p("for k, v := range %s {", x)
			}
			g.p("entry := 1 + len(k) + cfprotobuf.SizeOfLen(len(k)) + 1 + %s", g.sizeOfValue(f.val, "v"))
			g.p("n += %d + entry + cfprotobuf.SizeOfLen(entry)", tagSize)
			g.p("}")
			g.p("}")
		case f.repeated:
			g.p("for _, e := range %s {", x)
			g.p("n += %d + %s", tagSize, g.sizeOfValue(f.val, "e"))
			g.p("}")
		default:
			tagSize = len(tagBytes(tagOf(f.number, wireType(f.val))))
			g.p("if %s {", notZero(f.val, x))
			g.p("n += %d + %s", tagSize, g.sizeOfValue(f.val, x))
			g.p("}")
		}
	}
	if si.unknown {
		g.p("n += len(m.unknownFields)")
	}
	g.p("return n")
	g.p("}")
}

// sizeOfValue returns an expression for the size of the encoding of x
// without its tag.
func (g *generator) sizeOfValue(v value, x string) string {
	switch v.kind {
	case kString, kBytes:
		return fmt.Sprintf("len(%s) + cfprotobuf.SizeOfLen(len(%s))", x, x)
	case kBool:
		return "1"
	case kVarint:
		return fmt.Sprintf("cfprotobuf.SizeOfInt(%s)", x)
	case kZigzag:
		return fmt.Sprintf("cfprotobuf.SizeOfVarint(cfprotobuf.Zigzag(%s))", conv("int64", v.src, x))
	case kFixed:
		return strconv.Itoa(v.size)
	}
	// The size of a nil message is 0, which is how a nil element of a repeated
	// field and a nil map value are written: as an empty message.
	return fmt.Sprintf("cfprotobuf.SizeOfMessage(%s.%s())", x, g.method("Size"))
}

func (g *generator) marshal(si *structInfo) {
	size, toSized := g.method("Size"), g.method("MarshalToSizedBuffer")
	g.p("")
	g.p("// %s returns the Protobuf encoding of m.", g.method("Marshal"))
	g.p("func (m *%s) %s() ([]byte, error) {", si.name, g.method("Marshal"))
	g.p("if m == nil {")
	g.p("return nil, nil")
	g.p("}")
	g.p("b := make([]byte, m.%s())", size)
	g.p("n, err := m.%s(b)", toSized)
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("return b[:n], nil")
	g.p("}")

	g.p("")
	g.p("// %s writes the Protobuf encoding of m to the beginning of b, which must", g.method("MarshalTo"))
	g.p("// have room for %s bytes, and returns the number of bytes written.", size)
	g.p("func (m *%s) %s(b []byte) (int, error) {", si.name, g.method("MarshalTo"))
	g.p("return m.%s(b[:m.%s()])", toSized, size)
	g.p("}")

	g.p("")
	g.p("// %s writes the Protobuf encoding of m to the end of b, which", toSized)
	g.p("// must have room for %s bytes, and returns the number of bytes written.", size)
	g.p("func (m *%s) %s(b []byte) (int, error) {", si.name, toSized)
	g.p("if m == nil {")
	g.p("return 0, nil")
	g.p("}")
	// The buffer is filled from its end: a nested message is written first
	// and its length after it, so that no size is computed twice. It means
	// fields are written in reverse order.
	g.p("i := len(b)")
	if si.unknown {
		g.p("if m.unknownFields != nil {")
		g.p("i -= len(m.unknownFields)")
		g.p("copy(b[i:], m.unknownFields)")
		g.p("}")
	}
	for n := len(si.fields) - 1; n >= 0; n-- {
		f := si.fields[n]
		x := "m." + f.goName
		switch {
		case f.isMap:
			g.p("if len(%s) > 0 {", x)
			g.p("for k, v := range %s {", x)
			g.p("end := i")
			g.putValue(f.val, "v", false)
			g.putTag(tagOf(2, wireType(f.val)))
			g.p("i -= len(k)")
			g.p("copy(b[i:], k)")
			g.p("i = cfprotobuf.PutLen(b, i, len(k))")
			g.putTag(tagOf(1, 2))
			g.p("i = cfprotobuf.PutLen(b, i, end-i)")
			g.putTag(tagOf(f.number, 2))
			g.p("}")
			g.p("}")
		case f.repeated:
			g.p("for n := len(%s) - 1; n >= 0; n-- {", x)
			g.putValue(f.val, x+"[n]", false)
			g.putTag(tagOf(f.number, 2))
			g.p("}")
		default:
			g.p("if %s {", notZero(f.val, x))
			g.putValue(f.val, x, true)
			g.putTag(tagOf(f.number, wireType(f.val)))
			g.p("}")
		}
	}
	g.p("return len(b) - i, nil")
	g.p("}")
}

// putValue emits code writing the value x, without its tag, in front of what
// has been written so far. singular is set for a field which is only written
// when it does not hold the zero value.
func (g *generator) putValue(v value, x string, singular bool) {
	switch v.kind {
	case kString, kBytes:
		g.p("i -= len(%s)", x)
		g.p("copy(b[i:], %s)", x)
		g.p("i = cfprotobuf.PutLen(b, i, len(%s))", x)
	case kBool:
		if singular {
			// Only written when it is true.
			g.p("i--")
			g.p("b[i] = 1")
		} else {
			g.p("i--")
			g.p("b[i] = 0")
			g.p("if %s {", x)
			g.p("b[i] = 1")
			g.p("}")
		}
	case kVarint:
		g.p("i = cfprotobuf.PutInt(b, i, %s)", x)
	case kZigzag:
		g.p("i = cfprotobuf.PutVarint(b, i, cfprotobuf.Zigzag(%s))", conv("int64", v.src, x))
	case kFixed:
		bits := v.size * 8
		g.p("i -= %d", v.size)
		g.p("binary.LittleEndian.PutUint%d(b[i:], math.Float%dbits(%s))", bits, bits, conv(fmt.Sprintf("float%d", bits), v.src, x))
	case kMessage:
		g.p("{")
		g.p("size, err := %s.%s(b[:i])", x, g.method("MarshalToSizedBuffer"))
		g.p("if err != nil {")
		g.p("return 0, err")
		g.p("}")
		g.p("i -= size")
		g.p("i = cfprotobuf.PutLen(b, i, size)")
		g.p("}")
	}
}

func (g *generator) unmarshal(si *structInfo) {
	public, private := g.method("Unmarshal"), "unmarshal"+g.cfg.Suffix
	g.p("")
	g.p("// %s decodes the Protobuf encoding of a message from b into m. Fields", public)
	g.p("// which are not in b are left as they are. Everything decoded is copied out of")
	g.p("// b, which may be reused afterwards.")
	g.p("func (m *%s) %s(b []byte) error {", si.name, public)
	g.p("return m.%s(b, 0)", private)
	g.p("}")

	g.p("")
	g.p("func (m *%s) %s(b []byte, depth int) error {", si.name, private)
	if si.recursive {
		// The type can nest in itself, so the input decides how deep the
		// recursion goes. Bound it.
		g.p("depth++")
		g.p("if depth > cfprotobuf.MaxDepth {")
		g.p("return cfprotobuf.ErrTooDeep")
		g.p("}")
	}
	g.p("for i := 0; i < len(b); {")
	// A varint of one byte, which most tags, lengths and numbers are, is
	// decoded in place: a call is what would dominate otherwise.
	g.p("tag, next := uint64(b[i]), i+1")
	g.p("if tag >= 0x80 {")
	g.p("if tag, next = cfprotobuf.Varint(b, i); next < 0 {")
	g.p("return cfprotobuf.Error(next)")
	g.p("}")
	g.p("}")
	g.p("i = next")
	// The switch is on the field number alone: numbers are dense, which
	// lets the compiler use a jump table, where tags (the number together
	// with the wire type) would take a search. The wire type is checked in
	// the case, and a case which decoded its field goes on to the next one.
	single := len(si.fields) == 1
	if len(si.fields) > 0 {
		if !single {
			g.p("switch tag >> 3 {")
		}
		for _, f := range si.fields {
			x := "m." + f.goName
			wire := 2
			if !f.isMap && !f.repeated {
				wire = wireType(f.val)
			}
			if single {
				g.p("if tag == %d { // %s", tagOf(f.number, wire), f.goName)
			} else {
				g.p("case %d: // %s", f.number, f.goName)
				g.p("if tag&7 == %d {", wire)
			}
			switch {
			case f.isMap:
				g.getMapEntry(f, x)
			case f.repeated:
				if f.val.kind == kMessage {
					g.p("e := new(%s)", f.val.src)
				} else {
					g.p("var e %s", f.val.src)
				}
				g.getValue(f.val, "e", "b", "i", "next", private, "", true)
				g.p("%s = append(%s, e)", x, x)
			default:
				g.getValue(f.val, x, "b", "i", "next", private, "", false)
			}
			g.p("continue")
			g.p("}")
		}
		if !single {
			g.p("}")
		}
	}
	// Everything else is skipped: a field the type does not have, and also a
	// field it has which came with another wire type than its type has. The
	// second is how google.golang.org/protobuf treats it, a sender with a
	// newer or older schema is not an error.
	g.p("next = cfprotobuf.Skip(b, i, tag)")
	g.p("if next < 0 {")
	g.p("return cfprotobuf.Error(next)")
	g.p("}")
	if si.unknown && !g.cfg.DropUnknown {
		// Fields the type does not know are kept and written back when the
		// message is marshaled, as Protobuf implementations do.
		g.p("m.unknownFields = cfprotobuf.AppendUnknown(m.unknownFields, tag, b[i:next])")
	}
	g.p("i = next")
	g.p("}")
	g.p("return nil")
	g.p("}")
}

// getValue emits code decoding the value at buf[i] into x and moving i past
// it. fresh is set if x is a new variable rather than a field of a message
// which may have been decoded into before. next is a variable to keep an
// index in, declared by the caller. sfx is added to the names of variables
// the code declares, so that code emitted inside of other such code does not
// shadow them.
func (g *generator) getValue(v value, x, buf, i, next, private, sfx string, fresh bool) {
	from, to := "from"+sfx, "to"+sfx
	switch v.kind {
	case kString, kBytes, kMessage:
		g.getLength(buf, i, sfx)
		switch v.kind {
		case kString:
			g.p("s%s := %s[%s:%s]", sfx, buf, from, to)
			g.p("if !cfprotobuf.ShortASCII(s%s) && !cfprotobuf.ValidString(s%s) {", sfx, sfx)
			g.p("return cfprotobuf.ErrInvalidUTF8")
			g.p("}")
			g.p("%s = %s(s%s)", x, v.src, sfx)
		case kBytes:
			// A field which is present is not nil, even when it is empty.
			g.p("%s = append(%s[:0], %s[%s:%s]...)", x, x, buf, from, to)
			g.p("if %s == nil {", x)
			g.p("%s = %s{}", x, v.src)
			g.p("}")
		case kMessage:
			if !fresh {
				g.p("if %s == nil {", x)
				g.p("%s = new(%s)", x, v.src)
				g.p("}")
			}
			g.p("if err := %s.%s(%s[%s:%s], depth); err != nil {", x, private, buf, from, to)
			g.p("return err")
			g.p("}")
		}
		g.p("%s = %s", i, to)
	case kBool, kVarint, kZigzag:
		g.p("var v%s uint64", sfx)
		g.p("if %s < len(%s) && %s[%s] < 0x80 {", i, buf, buf, i)
		g.p("v%s, %s = uint64(%s[%s]), %s+1", sfx, next, buf, i, i)
		g.p("} else if v%s, %s = cfprotobuf.Varint(%s, %s); %s < 0 {", sfx, next, buf, i, next)
		g.p("return cfprotobuf.Error(%s)", next)
		g.p("}")
		switch v.kind {
		case kBool:
			g.p("%s = v%s != 0", x, sfx)
		case kVarint:
			g.p("%s = cfprotobuf.Int[%s](v%s)", x, v.src, sfx)
		default:
			g.p("%s = %s", x, conv(v.src, "int64", "cfprotobuf.Unzigzag(v"+sfx+")"))
		}
		g.p("%s = %s", i, next)
	case kFixed:
		bits := v.size * 8
		g.p("if len(%s)-%s < %d {", buf, i, v.size)
		g.p("return cfprotobuf.ErrTruncated")
		g.p("}")
		g.p("%s = %s", x, conv(v.src, fmt.Sprintf("float%d", bits), fmt.Sprintf("math.Float%dfrombits(binary.LittleEndian.Uint%d(%s[%s:]))", bits, bits, buf, i)))
		g.p("%s += %d", i, v.size)
	}
}

// getLength emits code decoding the length prefix at buf[i] into from and to,
// the bounds of the value, which are within buf.
func (g *generator) getLength(buf, i, sfx string) {
	from, to := "from"+sfx, "to"+sfx
	g.p("%s := %s + 1", from, i)
	g.p("var %s int", to)
	g.p("if %s < len(%s) && %s[%s] < 0x80 && int(%s[%s]) <= len(%s)-%s {", i, buf, buf, i, buf, i, buf, from)
	g.p("%s = %s + int(%s[%s])", to, from, buf, i)
	g.p("} else if %s, %s = cfprotobuf.Length(%s, %s); %s < 0 {", from, to, buf, i, from)
	g.p("return cfprotobuf.Error(%s)", from)
	g.p("}")
}

func (g *generator) getMapEntry(f field, x string) {
	g.getLength("b", "i", "")
	g.p("if %s == nil {", x)
	if f.val.kind == kMessage {
		g.p("%s = make(map[%s]*%s)", x, f.keySrc, f.val.src)
	} else {
		g.p("%s = make(map[%s]%s)", x, f.keySrc, f.val.src)
	}
	g.p("}")
	// An entry is a message of its own: the key is field 1, the value is
	// field 2, either may be missing and anything else is skipped.
	g.p("entry := b[from:to]")
	g.p("var key %s", f.keySrc)
	if f.val.kind == kMessage {
		// The value is there even when the entry does not have it, and an
		// entry which has it more than once merges them, which is how
		// google.golang.org/protobuf reads a map entry.
		g.p("val := new(%s)", f.val.src)
	} else {
		g.p("var val %s", f.val.src)
	}
	g.p("for j := 0; j < len(entry); {")
	g.p("entryTag := uint64(entry[j])")
	g.p("next = j + 1")
	g.p("if entryTag >= 0x80 {")
	g.p("if entryTag, next = cfprotobuf.Varint(entry, j); next < 0 {")
	g.p("return cfprotobuf.Error(next)")
	g.p("}")
	g.p("}")
	g.p("j = next")
	g.p("switch entryTag {")
	g.p("case %d:", tagOf(1, 2))
	g.getValue(value{kind: kString, src: f.keySrc}, "key", "entry", "j", "next", "", "Key", true)
	g.p("case %d:", tagOf(2, wireType(f.val)))
	g.getValue(f.val, "val", "entry", "j", "next", "unmarshal"+g.cfg.Suffix, "Val", true)
	g.p("default:")
	g.p("next = cfprotobuf.Skip(entry, j, entryTag)")
	g.p("if next < 0 {")
	g.p("return cfprotobuf.Error(next)")
	g.p("}")
	g.p("j = next")
	g.p("}")
	g.p("}")
	g.p("%s[key] = val", x)
	g.p("i = to")
}
